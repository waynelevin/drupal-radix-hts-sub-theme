import { build } from 'esbuild';
import fg from 'fast-glob';
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import {
  makeSassPlugin,
  stylelintPlugin,
  copyPlugin,
  bootstrapIconsPlugin,
  componentJsEntries,
} from './plugins.mjs';

// Per-component SCSS -> sibling .css (e.g. components/card/card.scss -> components/card/card.css).
const components = fg.sync('components/**/*.scss');

for (const file of components) {
  await build({
    entryPoints: [file],
    outfile: file.replace('.scss', '.css'),
    bundle: false,
    sourcemap: false,
    minify: true,
    plugins: [makeSassPlugin()]
  })
}

// Per-component JS: _name.js -> sibling name.js (the file Drupal SDC auto-attaches).
const jsEntries = componentJsEntries();
if (Object.keys(jsEntries).length > 0) {
  await build({
    entryPoints: jsEntries,
    outdir: '.',
    bundle: true,
    minify: true,
    sourcemap: false,
    external: ['/themes/*'],
  })
}

// Global theme bundle: main stylesheet + main script, plus assets and icons.
await build({
  entryPoints: {
    'css/main.style': 'src/scss/main.style.scss',
    'js/main.script': 'src/js/main.script.js',
  },
  bundle: true,
  minify: true,
  sourcemap: false,
  outdir: 'build',
  external: ['/themes/*'],
  plugins: [
    makeSassPlugin(),
    stylelintPlugin,
    copyPlugin(),
    bootstrapIconsPlugin
  ]
})

// Bootswatch variants: one full stylesheet per Bootswatch theme
// (build/css/bootswatch/NAME.css), selectable on the theme settings page.
// Each variant applies the theme's own variables first (so they win), then the
// Bootswatch variables, the normal theme stylesheet, and Bootswatch's rules.
const bootswatchDir = 'node_modules/bootswatch/dist';
if (existsSync(bootswatchDir)) {
  mkdirSync('src/scss/bootswatch', { recursive: true });
  const bootswatchEntries = {};
  for (const name of readdirSync(bootswatchDir).sort()) {
    if (!existsSync(`${bootswatchDir}/${name}/_variables.scss`)) {
      continue;
    }
    const entry = `src/scss/bootswatch/${name}.scss`;
    writeFileSync(entry, [
      '// Generated by build.mjs from the bootswatch package. Do not edit.',
      '@import "../base/variables";',
      `@import "~bootswatch/dist/${name}/variables";`,
      '@import "../main.style";',
      `@import "~bootswatch/dist/${name}/bootswatch";`,
      '',
    ].join('\n'));
    bootswatchEntries[`css/bootswatch/${name}`] = entry;
  }
  await build({
    entryPoints: bootswatchEntries,
    bundle: true,
    minify: true,
    sourcemap: false,
    outdir: 'build',
    external: ['/themes/*', 'https://*'],
    plugins: [makeSassPlugin()],
  });
}
